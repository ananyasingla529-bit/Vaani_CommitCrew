"""
Multilingual transliteration normalizer and cyber-bullying classification service.
Supports Hindi (Romanized), Hinglish, Punjabi (Romanized), and English.
Includes a clearly marked plug-in hook for production ML / LLM models.
"""

import re
import os
from typing import Dict, Any, Optional


def normalize_transliteration(text: str) -> str:
    """
    Standardizes phonetic spelling variants, asterisks, and @ symbols
    commonly used to evade basic keyword filters in Romanized Indic text.
    """
    normalized = text
    
    # Common obfuscation replacements
    replacements = [
        (r"k\*tta|kutta|kuttey|k\*tteya|k\*tte", "kutta"),
        (r"k\*meeni|kameeni|kameena|k\*meena", "kameena"),
        (r"b@stard|b\*stard|bastard", "bastard"),
        (r"bhos\*|bsdk|bhosd[i*]+", "bhosdika"),
        (r"m@r daloonga|mar dalunga|maar daloonga|m@r ja", "maar daloonga"),
        (r"kanj\*r|kanjar|k\*njar", "kanjar"),
        (r"thappad maro?onga|chaped maaran", "thappad marunga"),
        (r"lattan bhan dunga|lattan bhan doonga", "lattan bhan doonga"),
        (r"auka+t|aukat", "aukaat"),
        (r"chirkut", "chirkut"),
        (r"chapri", "chapri"),
        (r"bhosa?di", "bhosdi"),
    ]

    for pattern, replacement in replacements:
        normalized = re.sub(pattern, replacement, normalized, flags=re.IGNORECASE)

    return normalized


def detect_language(text: str) -> str:
    """
    Detects whether the Romanized sentence belongs to Hindi, Hinglish, Punjabi, or English.
    """
    lower = text.lower()

    # Punjabi Romanized markers
    punjabi_markers = [
        "oye", "mainu", "tainu", "tuhanu", "kitta", "kiven", "pind", 
        "lattan", "chittar", "saanu", "chaped", "wargi", "ehna", "ne", "ae"
    ]
    if any(re.search(rf"\b{word}\b", lower) for word in punjabi_markers):
        return "Punjabi (Romanized)"

    # Hindi Romanized markers
    hindi_markers = [
        "tu", "tera", "teri", "tere", "hai", "hain", "mai", "main", "kya", 
        "kyun", "yahan", "wahan", "karenge", "marunga", "saale", "chup", 
        "aurat", "aadmi", "ladki", "ladka", "sharam"
    ]
    has_hindi = any(re.search(rf"\b{word}\b", lower) for word in hindi_markers)

    # English tech/slang markers
    english_markers = [
        "meeting", "server", "channel", "code", "repo", "office", "report", 
        "discord", "video", "interview", "mentor", "hackathon"
    ]
    has_english = any(re.search(rf"\b{word}\b", lower) for word in english_markers)

    if has_hindi and has_english:
        return "Hinglish"
    if has_hindi:
        return "Hindi (Romanized)"
    return "English"


