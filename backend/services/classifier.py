def classify_rule_based(text: str, target_user: Optional[str] = None) -> Dict[str, Any]:
    """
    Rule-based classification fallback used when MOCK_MODE=True.
    Applies phonetic normalization and checks false positives, threats,
    harassment, hate speech, sexual content, and insults.
    """
    lower = text.lower()
    normalized = normalize_transliteration(text)
    language = detect_language(text)

    # Extract target handle if not explicitly provided
    if not target_user:
        mention = re.search(r"@([a-zA-Z0-9_]+)", text)
        if mention:
            target_user = f"@{mention.group(1)}"

    # 1. Check False Positives First
    false_positive_patterns = [
        (r"aag laga di|aag lagadi", "Metaphorical phrase 'aag laga di' (set on fire) used as enthusiastic praise for performance, not arson or threat."),
        (r"dead laughing|dying of laughter", "Hyperbolic internet idiom 'dead laughing' indicates amusement, with no threatening intent."),
        (r"pkill|kill the process|kill -9|zombie workers", "Standard UNIX operating system administration terminology referring to terminating a computing task."),
        (r"pagal hai yaar itna mast surprise", "'Pagal' (crazy) used affectionately in celebratory social banter regarding a birthday surprise."),
        (r"kill it (in|on) the (interview|presentation|stage|match)", "Idiomatic encouragement wishing success in performance or interview."),
    ]

    for pat, expl in false_positive_patterns:
        if re.search(pat, lower):
            return {
                "category": "Insult/Bullying",
                "severity": "low",
                "language": language,
                "normalized_text": normalized,
                "explanation": f"FALSE POSITIVE: {expl}",
                "target_user": target_user,
                "confidence": 0.94,
                "flagged": False,
            }

    # 2. Threat Detection
    threat_patterns = [
        r"m@r daloonga|mar dunga|maar daloonga|hospital|sir phod|lattan bhan|zinda nahi mudega|chaku|chapped|thappad|stab|goud dunga|gher lenge",
        r"kill you|murder|break your legs|shoot you|dox your address"
    ]
    if any(re.search(pat, lower) for pat in threat_patterns):
        return {
            "category": "Threat",
            "severity": "high",
            "language": language,
            "normalized_text": normalized,
            "explanation": "Explicit physical assault, lethal violence, or stalking threat detected in Romanized text.",
            "target_user": target_user,
            "confidence": 0.96,
            "flagged": True,
        }

    # 3. Sexual Content & Extortion
    sexual_patterns = [
        r"sex chat|private pics|leak your phone|figure hai|babe|nude|boobs|undress|ek raat ka kitna"
    ]
    if any(re.search(pat, lower) for pat in sexual_patterns):
        return {
            "category": "Sexual content",
            "severity": "high",
            "language": language,
            "normalized_text": normalized,
            "explanation": "Unsolicited sexual solicitation, extortion, or objectification directed at community participant.",
            "target_user": target_user,
            "confidence": 0.95,
            "flagged": True,
        }

    # 4. Hate Speech
    hate_patterns = [
        r"desh se bahar|north east|quota wale|feminists are cancer|community ke log|caste|bhagao yaha se"
    ]
    if any(re.search(pat, lower) for pat in hate_patterns):
        return {
            "category": "Hate speech",
            "severity": "high",
            "language": language,
            "normalized_text": normalized,
            "explanation": "Discriminatory rhetoric, xenophobic bias, or collective dehumanizing hate speech targeting protected groups.",
            "target_user": target_user,
            "confidence": 0.93,
            "flagged": True,
        }

    # 5. Targeted Harassment / Brigading / Doxxing
    harassment_patterns = [
        r"spam|dox|get you fired|career khatam|mass report|withdraw her nomination|pathetic|corrupt committee"
    ]
    if any(re.search(pat, lower) for pat in harassment_patterns):
        return {
            "category": "Harassment",
            "severity": "high" if "dox" in lower or "fired" in lower else "medium",
            "language": language,
            "normalized_text": normalized,
            "explanation": "Coordinated brigading, intimidation, or targeted campaign to harass an individual.",
            "target_user": target_user,
            "confidence": 0.91,
            "flagged": True,
        }

    # 6. Insults & Cyber-Bullying
    insult_patterns = [
        r"k\*tta|kutta|kameena|b@stard|bastard|bsdk|chirkut|chapri|idiot|loser|scumbag|chomu|bhikari|kanjar|k\*tti|aukaat"
    ]
    if any(re.search(pat, lower) for pat in insult_patterns):
        return {
            "category": "Insult/Bullying",
            "severity": "high" if "bsdk" in lower or "k*tti" in lower else "medium",
            "language": language,
            "normalized_text": normalized,
            "explanation": "Hostile personal insults, profane slurs, or demeaning abuse in Romanized Indic text.",
            "target_user": target_user,
            "confidence": 0.89,
            "flagged": True,
        }

    # 7. Clean / Mild
    return {
        "category": "Other",
        "severity": "low",
        "language": language,
        "normalized_text": normalized,
        "explanation": "No high-confidence toxic markers or threats detected. Passes community safety threshold.",
        "target_user": target_user,
        "confidence": 0.85,
        "flagged": False,
    }


def classify_text(text: str, target_user: Optional[str] = None) -> Dict[str, Any]:
    """
    Main classification entry point.
    First tries external model hook; if not configured or in mock mode, executes rule-based classifier.
    """
    external_result = classify_with_external_model(text, target_user)
    if external_result:
        return external_result
    return classify_rule_based(text, target_user)
